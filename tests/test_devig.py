# ---------------------------------------------------------------------------
# Тест 3: Сбалансированный рынок 50/50 (коэффициенты 2.0/2.0)
# ---------------------------------------------------------------------------


def test_devig_balanced_market(normalizer: OddsNormalizer) -> None:
    """
    Проверяет поведение девиггинга на сбалансированном рынке.

    Если оба исхода имеют одинаковые коэффициенты (2.0/2.0) —
    это идеально сбалансированный рынок без маржи (overround = 1.0).
    После девиггинга вероятности должны оставаться равными (0.5/0.5).

    Также тестируем рынок с маржой: 1.91/1.91 (overround ≈ 1.047).
    После девиггинга оба исхода должны получить вероятность 0.5.
    """
    # Идеально сбалансированный рынок без маржи
    balanced_odds = [2.0, 2.0]
    fair_odds_balanced = normalizer.devig_multiplicative(balanced_odds)

    assert abs(fair_odds_balanced[0] - 2.0) < 1e-9, (
        f"Для симметричного рынка 2.0/2.0 справедливый коэффициент должен остаться 2.0, "
        f"получено {fair_odds_balanced[0]}"
    )
    assert abs(fair_odds_balanced[1] - 2.0) < 1e-9

    # Рынок с маржой: 1.91/1.91 (типично для бинарных рынков)
    margined_odds = [1.91, 1.91]
    fair_odds_margined = normalizer.devig_multiplicative(margined_odds)

    # После девиггинга вероятности должны быть равными (0.5/0.5)
    prob_0 = 1.0 / fair_odds_margined[0]
    prob_1 = 1.0 / fair_odds_margined[1]
    assert abs(prob_0 - 0.5) < 1e-9, f"Ожидалась вероятность 0.5, получено {prob_0}"
    assert abs(prob_1 - 0.5) < 1e-9, f"Ожидалась вероятность 0.5, получено {prob_1}"


# ---------------------------------------------------------------------------
# Тест 4: Overround корректно определяется
# ---------------------------------------------------------------------------


def test_devig_overround(normalizer: OddsNormalizer) -> None:
    """
    Проверяет, что overround (сумма implied вероятностей) корректно
    вычисляется для типичных букмекерских линий.

    Тестовые случаи:
        - Рынок без маржи: overround = 1.0 (для коэффициентов 2.0/2.0).
        - Рынок с 5% маржой: overround ≈ 1.05.
        - Рынок с 10% маржой: overround ≈ 1.10.
    """
    # Рынок без маржи: 2.0/2.0 → overround = 1.0
    no_vig_odds = [2.0, 2.0]
    overround_no_vig = _compute_overround(no_vig_odds)
    assert (
        abs(overround_no_vig - 1.0) < 1e-10
    ), f"Overround для рынка без маржи должен быть 1.0, получено {overround_no_vig}"

    # Рынок с ~5% маржой: 1.91/1.91 → overround ≈ 1.047
    five_pct_odds = [1.91, 1.91]
    overround_5pct = _compute_overround(five_pct_odds)
    assert overround_5pct > 1.0, "Overround должен быть > 1.0 для рынка с маржой"
    assert (
        1.04 < overround_5pct < 1.06
    ), f"Ожидался overround ≈ 1.047 для 1.91/1.91, получено {overround_5pct:.4f}"

    # Рынок с высокой маржой (~10%): 1.80/1.80 → overround ≈ 1.111
    high_margin_odds = [1.80, 1.80]
    overround_high = _compute_overround(high_margin_odds)
    assert overround_high > 1.0
    assert (
        1.10 < overround_high < 1.12
    ), f"Ожидался overround ≈ 1.111 для 1.80/1.80, получено {overround_high:.4f}"


# ---------------------------------------------------------------------------
# Тест 5: Девиггинг сохраняет порядок вероятностей
# ---------------------------------------------------------------------------


def test_devig_preserves_relative_probs(normalizer: OddsNormalizer) -> None:
    """
    Проверяет, что после девиггинга относительный порядок вероятностей исходов
    сохраняется (наиболее вероятный исход остаётся наиболее вероятным).

    Сценарий: рынок с явным фаворитом.
        - Фаворит: 1.50 (implied prob ≈ 0.667)
        - Аутсайдер: 2.80 (implied prob ≈ 0.357)
        После девиггинга вероятность фаворита всё равно должна быть выше.
    """
    # Асимметричный рынок
    raw_odds = [1.50, 2.80]  # фаворит, аутсайдер

    original_probs = _odds_to_probs(raw_odds)
    assert original_probs[0] > original_probs[1], "Фаворит должен иметь выше вероятность"

    # Мультипликативный девиггинг
    fair_odds_mult = normalizer.devig_multiplicative(raw_odds)
    fair_probs_mult = _odds_to_probs(fair_odds_mult)
    assert (
        fair_probs_mult[0] > fair_probs_mult[1]
    ), "После мультипликативного девиггинга фаворит должен оставаться фаворитом"

    # Степенной девиггинг
    fair_odds_pow = normalizer.devig_power(raw_odds)
    fair_probs_pow = _odds_to_probs(fair_odds_pow)
    assert (
        fair_probs_pow[0] > fair_probs_pow[1]
    ), "После степенного девиггинга фаворит должен оставаться фаворитом"


# ---------------------------------------------------------------------------
# Тест 6: Усреднение по нескольким букмекерам
# ---------------------------------------------------------------------------


def test_market_average_devigged(normalizer: OddsNormalizer) -> None:
    """
    Проверяет метод усреднения справедливых вероятностей по нескольким букмекерам.

    Сценарий:
        - 3 букмекера с незначительно различающимися коэффициентами.
        - После усреднения вероятности должны суммироваться в ≈ 1.0.
        - Усреднённые справедливые коэффициенты должны быть в разумном диапазоне.
    """
    # Три букмекера с близкими, но разными коэффициентами для двух исходов
    book_odds = {
        "pinnacle": [2.05, 1.87],
        "bet365": [2.00, 1.83],
        "betfair": [2.10, 1.90],
    }

    avg_fair_odds = normalizer.market_average_devigged(book_odds)

    assert len(avg_fair_odds) == 2, f"Ожидалось 2 исхода, получено {len(avg_fair_odds)}"

    # Сумма вероятностей должна быть ≈ 1.0
    prob_sum = sum(1.0 / o for o in avg_fair_odds)
    assert (
        abs(prob_sum - 1.0) < 1e-6
    ), f"Сумма вероятностей после усреднения: {prob_sum:.8f}, ожидалось ≈ 1.0"

    # Все коэффициенты должны быть > 1.0
    for i, o in enumerate(avg_fair_odds):
        assert o > 1.0, f"Коэффициент [{i}] = {o} <= 1.0 (некорректный)"


# ---------------------------------------------------------------------------
# Тест 7: Экстремальные коэффициенты
# ---------------------------------------------------------------------------


def test_devig_extreme_odds(normalizer: OddsNormalizer) -> None:
    """
    Проверяет корректную обработку граничных значений коэффициентов.

    Сценарий 1: Очень высокие коэффициенты (маловероятные события).
        odds = [1.02, 25.0] — явный аутсайдер с коэффициентом 25.
    Сценарий 2: Трёхисходный рынок с коэффициентом 1.01 (почти уверенный исход).
        odds = [1.01, 20.0, 30.0]
    """
    # Сценарий 1: высокие коэффициенты для аутсайдера
    extreme_odds = [1.02, 25.0]
    fair_extreme = normalizer.devig_multiplicative(extreme_odds)

    assert len(fair_extreme) == 2
    prob_sum_extreme = sum(1.0 / o for o in fair_extreme)
    assert (
        abs(prob_sum_extreme - 1.0) < 1e-9
    ), f"Экстремальные коэффициенты: сумма вероятностей = {prob_sum_extreme}, ожидалось 1.0"
    # Фаворит с 1.02 должен иметь очень высокую вероятность
    fav_prob = 1.0 / fair_extreme[0]
    assert (
        fav_prob > 0.95
    ), f"Вероятность фаворита (odds=1.02) должна быть > 95%, получено {fav_prob:.2%}"

    # Сценарий 2: почти уверенный исход в трёхисходном рынке
    near_certain_odds = [1.01, 20.0, 30.0]
    fair_near_certain = normalizer.devig_multiplicative(near_certain_odds)

    assert len(fair_near_certain) == 3
    prob_sum_nc = sum(1.0 / o for o in fair_near_certain)
    assert (
        abs(prob_sum_nc - 1.0) < 1e-9
    ), f"Почти уверенный исход: сумма вероятностей = {prob_sum_nc}, ожидалось 1.0"
