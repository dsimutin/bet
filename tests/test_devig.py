"""
Тесты для функций удаления маржи букмекера (девиггинга).

Проверяются мультипликативный и степенной методы девиггинга,
а также усреднение справедливых вероятностей по нескольким букмекерам.
Все тесты используют синтетические данные без внешних зависимостей.
"""

from __future__ import annotations

import pytest

from src.normalize.odds_normalizer import OddsNormalizer

