# ---------------------------------------------------------------------------
# Вспомогательные функции
# ---------------------------------------------------------------------------


def _odds_to_probs(odds: list[float]) -> list[float]:
    """Конвертирует список коэффициентов в implied вероятности."""
    return [1.0 / o for o in odds]


def _compute_overround(odds: list[float]) -> float:
    """Вычисляет overround (сумму implied вероятностей) для списка коэффициентов."""
    return sum(1.0 / o for o in odds)


# ---------------------------------------------------------------------------
# Тест 1: Мультипликативный девиггинг — сумма вероятностей = 1.0
# ---------------------------------------------------------------------------


def test_devig_multiplicative_sums_to_one(normalizer: OddsNormalizer) -> None:
    """
    Проверяет, что после мультипликативного девиггинга сумма
    implied вероятностей (из обратных коэффициентов) равна 1.0.

    Используется трёхисходный рынок с маржой ~5%:
        Коэффициенты: 2.50, 3.20, 2.80 (overround ≈ 1.05).
        После девиггинга сумма 1/o должна быть ≈ 1.0.
    """
    # Трёхисходный рынок (например, домашняя победа / ничья / гостевая победа)
    raw_odds = [2.50, 3.20, 2.80]

    # Проверяем наличие маржи в исходных коэффициентах
    original_overround = _compute_overround(raw_odds)
    assert original_overround > 1.0, "Исходные коэффициенты должны иметь overround > 1.0"

    # Применяем девиггинг
    fair_odds = normalizer.devig_multiplicative(raw_odds)
    assert len(fair_odds) == len(raw_odds), "Количество коэффициентов должно совпадать"

    # Проверяем, что сумма вероятностей ≈ 1.0
    prob_sum = sum(1.0 / o for o in fair_odds)
    assert abs(prob_sum - 1.0) < 1e-9, (
        f"Сумма вероятностей после мультипликативного девиггинга: {prob_sum:.10f}, "
        f"ожидалось 1.0 (отклонение > 1e-9)"
    )


